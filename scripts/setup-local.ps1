$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$certDir = Join-Path $projectRoot '.docker'
New-Item -ItemType Directory -Force -Path $certDir | Out-Null

# Public certificates only. Private keys are never exported.
$certificates = @(Get-ChildItem Cert:\LocalMachine\Root) + @(Get-ChildItem Cert:\CurrentUser\Root)
$pem = foreach ($cert in ($certificates | Sort-Object Thumbprint -Unique)) {
    "-----BEGIN CERTIFICATE-----`n" +
    [Convert]::ToBase64String($cert.RawData, [Base64FormattingOptions]::InsertLineBreaks) +
    "`n-----END CERTIFICATE-----"
}
[IO.File]::WriteAllText((Join-Path $certDir 'local-ca.pem'), ($pem -join "`n"), [Text.Encoding]::ASCII)

$services = @('client', 'db-migrate', 'gateway', 'auth-service', 'lounge-service', 'reservation-service', 'payment-service', 'notification-service')
$override = "# Generated by scripts/setup-local.ps1; local certificate trust only.`nservices:`n"
foreach ($service in $services) {
    $override += "  ${service}:`n    build:`n      secrets:`n        - npm_ca`n"
    $override += "    environment:`n      NODE_EXTRA_CA_CERTS: /run/local-ca.pem`n    volumes:`n      - ./.docker/local-ca.pem:/run/local-ca.pem:ro`n"
}
$override += "secrets:`n  npm_ca:`n    file: ./.docker/local-ca.pem`n"
[IO.File]::WriteAllText((Join-Path $projectRoot 'docker-compose.override.yml'), $override, [Text.Encoding]::ASCII)
Write-Host 'Local Docker certificate trust configured.'
